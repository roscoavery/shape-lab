/**
 * Writes docs/coach-ed/image-audit.md from the media library records.
 * Run: npx tsx scripts/coach-ed-gen-audit.ts
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { LICENSE_LABELS, MEDIA_ASSETS, MEDIA_SLOTS } from '../src/content/coachEd/media.ts'
import { loadAllLessons } from '../src/content/coachEd/registry.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'docs/coach-ed/image-audit.md')

export async function buildAuditSource(): Promise<string> {
  const lessons = await loadAllLessons()
  const by = (s: string) => MEDIA_ASSETS.filter((a) => a.status === s)
  const row = (a: (typeof MEDIA_ASSETS)[number]) =>
    `| ${a.id} | ${a.status} | ${LICENSE_LABELS[a.license]} | ${a.creator.replace(/\|/g, '/')} | [page](${a.sourcePageUrl}) | ${a.localPath ?? 'not hosted'} | ${[...a.conditionIds, ...a.lessonIds].join(', ') || 'unassigned'} |`
  const head = '| Id | Status | License | Creator | Source | Hosted copy | Used by |\n| --- | --- | --- | --- | --- | --- | --- |'
  const noApproved = MEDIA_SLOTS.filter((s) => !s.assetIds.some((id) => MEDIA_ASSETS.find((a) => a.id === id)?.status === 'approved'))
  const slotUse = (slotId: string) =>
    lessons.filter((l) => l.blocks.some((b) => b.kind === 'figure' && b.slotId === slotId)).map((l) => l.id)
  const lines: string[] = []
  lines.push('# Coach education image audit', '')
  lines.push('Generated by `scripts/coach-ed-gen-audit.ts` from `src/content/coachEd/media.ts`. Re-run `npm run coach-ed:gen` after any media change.', '')
  lines.push('## Rules applied', '')
  lines.push(
    '- No AI-generated images. Every record comes from a named source with a license page.',
    '- Preferred sources: Servier Medical Art (CC BY 4.0), Wikimedia Commons, AnatomyTOOL, CDC Public Health Image Library.',
    '- Rejected: NonCommercial, NoDerivatives where a change was needed, unclear, or unverifiable licenses; any image whose anatomy could not be checked.',
    '- Wikimedia Commons licenses were read from the Commons file-description API (`extmetadata`). The raw responses, file hashes, and hosted paths are in `docs/coach-ed/media-verification-log.json`.',
    '- An image shows to coaches only when its status is `approved`. Otherwise the lesson shows "Verified visual pending". Admins see non-approved candidates as a preview with approve and reject controls.',
    '- "Approved" by this build was a visual check of printed plate labels against the file text, not a clinician review. Admins can withdraw any approval.',
    '',
  )
  lines.push('## Counts', '')
  for (const s of ['approved', 'anatomy_pending', 'license_verified', 'license_pending', 'candidate', 'rejected']) {
    lines.push(`- ${s}: ${by(s).length}`)
  }
  lines.push('', '## Imported and approved', '', head, ...by('approved').map(row), '')
  lines.push('## Imported, waiting for anatomy review', '', head, ...by('anatomy_pending').map(row), '')
  lines.push('## Rejected candidates', '', '| Id | License | Why |', '| --- | --- | --- |')
  for (const a of by('rejected')) lines.push(`| ${a.id} | ${LICENSE_LABELS[a.license]} | ${(a.rejectionReason ?? '').replace(/\|/g, '/')} |`)
  lines.push('', '## Slots with no approved image', '', '| Slot | Needs | Candidate ids | Lessons |', '| --- | --- | --- | --- |')
  for (const s of noApproved) lines.push(`| ${s.id} | ${s.need} | ${s.assetIds.join(', ')} | ${slotUse(s.id).join(', ') || 'none'} |`)
  lines.push('', '## Lessons that still list visuals as needed', '')
  for (const l of lessons.filter((x) => x.visualNeeded?.length)) lines.push(`- **${l.id}**: ${l.visualNeeded!.join('; ')}`)
  lines.push(
    '',
    '## Existing education images (not changed)',
    '',
    '- `src/assets/references/` and `public/references/` (53 files): gym shape and skill reference photos. These are ShapeLab teaching photos, not medical or anatomy images. Retained as is. Their attribution is the gym coach library and is out of scope for medical visual verification.',
    '- `src/assets/coach-stills/` and `public/learn/coach-stills/`: coach stills. Retained as is.',
    '- `public/learn/progression-levels.png` and `docs/infographics/`: ShapeLab teaching graphics. Retained as is.',
    '- No existing lesson displayed an anatomy or injury image, so no existing medical visual was replaced. The new Coach education panel adds visuals through media slots only.',
    '',
    '## Sources checked',
    '',
    '- Wikimedia Commons: used. Five candidates imported, four rejected.',
    '- Servier Medical Art: site-wide license confirmed as CC BY 4.0, but no matching figure was imported in this pass. Pending.',
    '- AnatomyTOOL and CDC PHIL: not searched in this pass. Pending.',
    '',
  )
  return lines.join('\n')
}

if (process.argv[1] && process.argv[1].endsWith('coach-ed-gen-audit.ts')) {
  writeFileSync(out, await buildAuditSource())
  console.log(`wrote ${out}`)
}
