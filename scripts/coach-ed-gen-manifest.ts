/**
 * Writes server/coachEd/manifest.generated.ts: plain ids and license facts the
 * server needs to validate review and media changes without importing the
 * client content tree. Run: npx tsx scripts/coach-ed-gen-manifest.ts
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { CONDITION_INDEX } from '../src/content/coachEd/conditions/index.generated.ts'
import { MEDIA_ASSETS } from '../src/content/coachEd/media.ts'
import { loadAllLessons } from '../src/content/coachEd/registry.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'server/coachEd/manifest.generated.ts')

export async function buildManifestSource(): Promise<string> {
  const lessons = (await loadAllLessons()).map((l) => ({ id: l.id, review: l.review }))
  const conditions = CONDITION_INDEX.map((c) => ({ id: c.id, completeness: c.completeness, review: c.review }))
  const media = MEDIA_ASSETS.map((m) => ({
    id: m.id,
    status: m.status,
    license: m.license,
    commercialUseAllowed: m.commercialUseAllowed,
    hasEvidence: Boolean(m.verificationEvidence && m.verifiedOn),
    hasHostedCopy: Boolean(m.localPath),
    hasCredit: Boolean(m.creditLine),
    hasAlt: Boolean(m.altText),
  }))
  return `// Generated by scripts/coach-ed-gen-manifest.ts. Do not edit by hand.
export type ManifestMedia = {
  id: string
  status: string
  license: string
  commercialUseAllowed: boolean
  hasEvidence: boolean
  hasHostedCopy: boolean
  hasCredit: boolean
  hasAlt: boolean
}

export const MANIFEST = {
  conditions: ${JSON.stringify(conditions)} as { id: string; completeness: string; review: string }[],
  lessons: ${JSON.stringify(lessons)} as { id: string; review: string }[],
  media: ${JSON.stringify(media, null, 2)} as ManifestMedia[],
}
`
}

if (process.argv[1] && process.argv[1].endsWith('coach-ed-gen-manifest.ts')) {
  writeFileSync(out, await buildManifestSource())
  console.log(`wrote ${out}`)
}
