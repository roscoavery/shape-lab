/**
 * Splits content-src/coach-ed/questions.raw.ts into
 *   - src/content/coachEd/questions/bank.generated.ts   (no answers, bundled)
 *   - server/coachEd/answers.generated.ts               (answers, server only)
 * Run: npx tsx scripts/coach-ed-gen-questions.ts
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { RAW_QUESTIONS } from '../content-src/coach-ed/questions.raw'
import type { QuestionAnswer, QuestionPublic } from '../src/content/coachEd/types.ts'

type ServerQuestion = QuestionAnswer & { topicId: string; critical: boolean }

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outBank = join(root, 'src/content/coachEd/questions/bank.generated.ts')
const outAnswers = join(root, 'server/coachEd/answers.generated.ts')

function hash(s: string): number {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}

/** Deterministic id-seeded shuffle so the correct choice is not always first. */
function shuffleIndexes(seed: string): number[] {
  const idx = [0, 1, 2, 3]
  let h = hash(seed)
  for (let i = idx.length - 1; i > 0; i--) {
    h = Math.imul(h ^ (h >>> 15), 2246822507) >>> 0
    const j = h % (i + 1)
    ;[idx[i], idx[j]] = [idx[j], idx[i]]
  }
  return idx
}

const DIFF = { f: 'foundation', a: 'applied', x: 'advanced' } as const
const LETTERS = ['a', 'b', 'c', 'd']

export function buildQuestionSources(): { bank: string; answers: string } {
  const pub: QuestionPublic[] = []
  const ans: ServerQuestion[] = []
  for (const q of RAW_QUESTIONS) {
    const order = shuffleIndexes(q.id)
    const choices = order.map((srcIdx, pos) => ({ id: LETTERS[pos], label: q.c[srcIdx] }))
    const answerId = LETTERS[order.indexOf(0)]
    pub.push({
      id: q.id,
      topicId: q.topic,
      kind: q.scenario ? 'scenario' : 'single',
      difficulty: DIFF[q.d],
      critical: q.crit === true,
      prompt: q.q,
      choices,
      sourceIds: q.src,
    })
    ans.push({ id: q.id, topicId: q.topic, critical: q.crit === true, answerId, explain: q.why })
  }
  return {
    bank: `// Generated by scripts/coach-ed-gen-questions.ts. Do not edit by hand.
// Contains no answers. Answer keys live in server/coachEd/answers.generated.ts.
import type { QuestionPublic } from '../types.ts'

export const QUESTION_BANK: QuestionPublic[] = ${JSON.stringify(pub, null, 2)}
`,
    answers: `// Generated by scripts/coach-ed-gen-questions.ts. Do not edit by hand.
// Server only. Nothing under src/ may import this file.
import type { QuestionAnswer } from '../../src/content/coachEd/types.ts'

export type ServerQuestion = QuestionAnswer & { topicId: string; critical: boolean }

export const QUESTION_ANSWERS: ServerQuestion[] = ${JSON.stringify(ans, null, 2)}
`,
  }
}

if (process.argv[1] && process.argv[1].endsWith('coach-ed-gen-questions.ts')) {
  const { bank, answers } = buildQuestionSources()
  writeFileSync(outBank, bank)
  writeFileSync(outAnswers, answers)
  console.log(`wrote ${RAW_QUESTIONS.length} questions`)
}
